function tags(material: string[], flags: string[], behavior: string[] = []): TagSetLike {
  return {
    material: new Set(material),
    temperature: 'normal',
    state: new Set(['normal']),
    behavior: new Set(behavior),
    flags: new Set(flags),
  };
}

